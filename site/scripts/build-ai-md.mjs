// Post-build: write dist/llms.txt and a .md copy of every public page, from the built HTML.
// Usage: node scripts/build-ai-md.mjs [distDir]   (default: dist)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { parse, pageMeta, mainNodes, toMarkdown, sitemapPaths, htmlFile, mdFile } from "./ai-md.mjs"

const dist = process.argv[2] ?? "dist"
const paths = sitemapPaths(readFileSync(join(dist, "sitemap.xml"), "utf8"))

const pages = paths.map((p) => {
  const root = parse(readFileSync(join(dist, htmlFile(p)), "utf8"))
  const meta = pageMeta(root)
  if (!meta.title || !meta.description || !meta.canonical) throw new Error(`${p}: missing title/description/canonical`)
  if (/[\r\n]/.test(meta.title + meta.description)) throw new Error(`${p}: multi-line title/description`)
  const md = toMarkdown(mainNodes(root), meta.canonical)
  const out = join(dist, mdFile(p))
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, md)
  return { path: p, md: mdFile(p), ...meta }
})

// llms.txt: only strings already published on the pages (title, meta description, site name),
// plus the neutral structural headings "Pages" and "Blog".
const home = pages.find((p) => p.path === "/")
if (!home) throw new Error("home page missing from sitemap")
const item = (p) => `- [${p.title}](${p.canonical}): ${p.description}`
const blog = pages.filter((p) => p.path.startsWith("/blog/"))
const rest = pages.filter((p) => !p.path.startsWith("/blog/"))
const llms = [
  `# ${home.siteName}`,
  "",
  `> ${home.description}`,
  "",
  "## Pages",
  "",
  ...rest.map(item),
  "",
  "## Blog",
  "",
  ...blog.map(item),
  "",
].join("\n")
writeFileSync(join(dist, "llms.txt"), llms)

// Headers for the generated files (Cloudflare Pages _headers). One explicit rule per path so
// nothing depends on wildcard matching; the same bytes are served to every client.
const rules = [
  "",
  "# generated by scripts/build-ai-md.mjs",
  "/llms.txt",
  "  Content-Type: text/plain; charset=utf-8",
  ...pages.flatMap((p) => [
    `/${p.md}`,
    "  Content-Type: text/markdown; charset=utf-8",
    `  Link: <${p.canonical}>; rel="canonical"`,
  ]),
  "",
].join("\n")
const hp = join(dist, "_headers")
const prev = readFileSync(hp, "utf8").replace(/\n# generated by scripts\/build-ai-md\.mjs[\s\S]*$/, "\n")
writeFileSync(hp, prev.replace(/\n*$/, "\n") + rules)

console.log(`ai-md: wrote llms.txt and ${pages.length} .md files`)
